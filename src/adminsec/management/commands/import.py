"""Command for importing data from a json file."""

import json
import traceback
from datetime import datetime

import pghistory
from django.contrib import auth
from django.core.management.base import BaseCommand
from django.db import transaction
from django.db.models import Count

from adminsec.models import HpcaccessState
from usersec.models import HpcGroup, HpcProject, HpcUser

User = auth.get_user_model()


SUFFIX_MAPPING = {
    "c": "@CHARITE",
    "m": "@MDC-BERLIN",
}


def login_name(username):
    """Map an HPC username such as ``alice_c`` to its Django username, or None if unknown."""
    ldap_user, _, suffix = username.rpartition("_")
    if ldap_user and suffix in SUFFIX_MAPPING:
        return f"{ldap_user}{SUFFIX_MAPPING[suffix]}"
    return None


class Command(BaseCommand):
    help = (
        "Import HPC objects from a json file. By default, this command runs in "
        "dry-run mode and only prints a summary of the differences between the "
        "objects in the database and the json file.\n\n"
        "New objects are created, existing objects are updated as needed, and "
        "any missing objects are reported (although never expected). For "
        'existing objects, the fields "consented_to_terms", "expiration", and '
        '"resources_used" are not modified by this command since the values '
        "generated by hpc-access-cli for the json file are arbitrary."
    )

    def _warn(self, msg):
        self.stderr.write(f"Warning: {msg}")

    def _save_changes(self, obj, changes):
        """Apply ``changes`` to ``obj`` and write only those columns.

        The objects were loaded when the update plan was built, so a full ``save()`` would
        overwrite columns the import does not manage (e.g. ``consented_to_terms`` or
        ``expiration``) with stale values if they were modified in the meantime.
        """
        if not changes:
            return
        for field, value in changes.items():
            setattr(obj, field, value)
        update_fields = set(changes)
        if hasattr(obj, "date_modified"):
            # auto_now only sets fields that are listed in update_fields
            update_fields.add("date_modified")
        obj.save(update_fields=sorted(update_fields))

    def _read_hpcaccess_state(self, cluster_state):
        """Read and normalize the json file from hpc-access-cli"""
        with open(cluster_state, "r") as jsonfile:
            hpc_state = HpcaccessState(**json.load(jsonfile))
        # Validate internal references. Delegate and member references to a skipped user
        # are kept aside as "skipped_delegate" and "skipped_members", so that existing
        # objects keep them (see the update plans).
        skipped = {}
        for hpc_user_key in list(hpc_state.hpc_users.keys()):
            data = hpc_state.hpc_users[hpc_user_key]
            primary_group = data["primary_group"]
            if primary_group in hpc_state.hpc_projects:
                self._warn(
                    f"Primary_group {primary_group} for user {data['username']} "
                    "is a project. This user will be skipped."
                )
            elif primary_group and primary_group not in hpc_state.hpc_groups:
                self._warn(
                    "Malformed input: missing primary_group reference "
                    f"({data['primary_group']}) for user {data['username']}. "
                    "This user will be skipped."
                )
            elif not login_name(data["username"]):
                self._warn(
                    f"Malformed input: username {data['username']} does not end in a known "
                    f"suffix ({', '.join(SUFFIX_MAPPING)}). This user will be skipped."
                )
            else:
                continue
            skipped[hpc_user_key] = data["username"]
            del hpc_state.hpc_users[hpc_user_key]
        for hpc_group_key in list(hpc_state.hpc_groups.keys()):
            data = hpc_state.hpc_groups[hpc_group_key]
            if data["owner"] not in hpc_state.hpc_users:
                self._warn(
                    "Malformed input: missing owner reference "
                    f"({data['owner']}) for group {data['name']}. "
                    "This group will not have an owner."
                )
                data["owner"] = None
            data["skipped_delegate"] = skipped.get(data["delegate"])
            if data["skipped_delegate"]:
                self._warn(
                    f"Skipped user {data['skipped_delegate']} is the delegate of group "
                    f"{data['name']}. The group keeps its current delegate."
                )
                data["delegate"] = None
            elif data["delegate"] and data["delegate"] not in hpc_state.hpc_users:
                self._warn(
                    "Malformed input: missing delegate reference "
                    f"({data['delegate']}) for group {data['name']}. "
                    "This group will not have a delegate."
                )
                data["delegate"] = None
        for hpc_project_key in list(hpc_state.hpc_projects.keys()):
            data = hpc_state.hpc_projects[hpc_project_key]
            if data["group"] not in hpc_state.hpc_groups:
                self._warn(
                    "Malformed input: missing group reference "
                    f"({data['group']}) for project {data['name']}. "
                    "This project will be skipped."
                )
                del hpc_state.hpc_projects[hpc_project_key]
                continue
            data["skipped_delegate"] = skipped.get(data["delegate"])
            if data["skipped_delegate"]:
                self._warn(
                    f"Skipped user {data['skipped_delegate']} is the delegate of project "
                    f"{data['name']}. The project keeps its current delegate."
                )
                data["delegate"] = None
            elif data["delegate"] and data["delegate"] not in hpc_state.hpc_users:
                self._warn(
                    "Malformed input: missing delegate reference "
                    f"({data['delegate']}) for project {data['name']}. "
                    "This project will not have a delegate."
                )
                data["delegate"] = None
            data["skipped_members"] = [
                skipped[member_uuid] for member_uuid in data["members"] if member_uuid in skipped
            ]
            if data["skipped_members"]:
                self._warn(
                    f"Skipped users {data['skipped_members']} are members of project "
                    f"{data['name']}. Existing memberships are kept, new ones are not added."
                )
            missing_members = [
                member_uuid
                for member_uuid in data["members"]
                if member_uuid not in hpc_state.hpc_users and member_uuid not in skipped
            ]
            if missing_members:
                self._warn(
                    "Malformed input: missing member references "
                    f"({missing_members}) for project {data['name']}. "
                    "These members will be skipped."
                )
            data["members"] = [
                member_uuid for member_uuid in data["members"] if member_uuid in hpc_state.hpc_users
            ]

        # Sanitize fields
        for hpc_user_key in list(hpc_state.hpc_users.keys()):
            data = hpc_state.hpc_users[hpc_user_key]
            data["login_name"] = login_name(data["username"])
            data["first_name"] = data["first_name"].strip() if data["first_name"] else ""
            data["last_name"] = data["last_name"].strip() if data["last_name"] else ""
            data["name"] = data["full_name"].strip() if data["full_name"] else ""
            data["display_name"] = data["display_name"].strip() if data["display_name"] else ""
            data["phone"] = data["phone_number"]

        # Detect duplicated GIDs
        all_gids = set()
        for data in hpc_state.hpc_groups.values():
            if data["gid"] in all_gids:
                self._warn(f"Duplicate gid detected: {data['gid']}")
            all_gids.add(data["gid"])
        for data in hpc_state.hpc_projects.values():
            if data["gid"] in all_gids:
                self._warn(f"Duplicate gid detected: {data['gid']}")
            all_gids.add(data["gid"])

        return hpc_state

    def _users_update_plan(self, cli_import):
        usernames = {data["login_name"] for data in cli_import.hpc_users.values()}
        existing = User.objects.annotate(hpcuser_count=Count("hpcuser_user")).exclude(
            hpcuser_count=0
        )
        all = {obj.username: obj for obj in User.objects.filter(username__in=usernames)}
        update = {
            # new objects
            "added": [],
            # tuple of (old, updated_fields) objects
            "changed": [],
            # queryset of old objects that are missing from the imported file
            "missing": existing.exclude(username__in=usernames),
            # count of existing and active objects
            "count": existing.count(),
        }
        for _uuid, data in cli_import.hpc_users.items():
            old = all.get(data["login_name"])
            if not old:
                new = User(
                    first_name=data["first_name"],
                    last_name=data["last_name"],
                    name=data["name"],
                    display_name=data["display_name"],
                    email=data["email"],
                    is_staff=False,
                    is_superuser=False,
                    is_hpcadmin=False,
                    consented_to_terms=False,
                    phone=data["phone"],
                    username=data["login_name"],
                )
                all[new.username] = new
                update["added"].append(new)
                continue
            changes = {}
            for field in ("first_name", "last_name", "name", "display_name", "email", "phone"):
                if (new_field := data[field]) != getattr(old, field):
                    changes[field] = new_field
            if changes:
                if not old.is_active:
                    self._warn(f'User "{old.username}" is not active, but their data changed.')
                update["changed"].append((old, changes))
        return all, update

    def _hpc_users_update_plan(self, cli_import, users):
        usernames = {data["username"] for data in cli_import.hpc_users.values()}
        existing = HpcUser.objects.select_for_update()
        all = {obj.username: obj for obj in existing.filter(username__in=usernames)}
        update = {
            "added": [],
            "changed": [],
            "missing": existing.exclude(username__in=usernames),
            "count": existing.count(),
        }
        for uuid, data in cli_import.hpc_users.items():
            fk_user = users.get(data["login_name"])
            if not fk_user:
                self.stderr.write(
                    f'Error: HpcUser "{data["username"]}" does not have an associated User account.'
                )
                raise KeyError(data["login_name"])
            if data["primary_group"]:
                if data["primary_group"] in cli_import.hpc_groups:
                    primary_group_name = cli_import.hpc_groups[data["primary_group"]]["name"]
                elif data["primary_group"] in cli_import.hpc_projects:
                    primary_group_name = cli_import.hpc_projects[data["primary_group"]]["name"]
                else:
                    # This should never happen because we check for missing references
                    # in _read_hpcaccess_state()
                    self.stderr.write(
                        f"Error: Primary group {data['primary_group']} not found "
                        f"for user {data['username']}"
                    )
                    raise KeyError(data["primary_group"])
            else:
                primary_group_name = None
            old = all.get(data["username"])
            if not old:
                new = HpcUser(
                    uuid=uuid,
                    user=fk_user,
                    resources_requested=data["resources_requested"],
                    resources_used=data["resources_used"],
                    creator=self.worker_user,
                    status=data["status"],
                    home_directory=data["home_directory"],
                    primary_group=HpcGroup(name=primary_group_name),
                    expiration=datetime.fromisoformat(data["expiration"]),
                    login_shell=data["login_shell"],
                    username=data["username"],
                    uid=data["uid"],
                )
                all[new.username] = new
                update["added"].append(new)
                continue
            changes = {}
            if old.user is None or data["login_name"] != old.user.username:
                changes["user"] = fk_user
            if (
                old.primary_group
                and old.primary_group.name != primary_group_name
                or not old.primary_group
                and primary_group_name
            ):
                changes["primary_group"] = primary_group_name
            for field in (
                "resources_requested",
                "status",
                "home_directory",
                "login_shell",
                "uid",
            ):
                if (new_field := data[field]) != getattr(old, field):
                    changes[field] = new_field
            if changes:
                if old.user and not old.user.is_active:
                    self._warn(
                        f'The user associated with "{old.username}" is not active, '
                        "but their Hpc data changed."
                    )
                update["changed"].append((old, changes))
        return all, update

    def _hpc_groups_update_plan(self, cli_import, hpc_users):
        names = {data["name"] for data in cli_import.hpc_groups.values()}
        existing = HpcGroup.objects.select_for_update()
        all = {obj.name: obj for obj in existing.filter(name__in=names)}
        update = {
            "added": [],
            # tuple of (old, changed_fields, members)
            "changed": [],
            "missing": existing.exclude(name__in=names),
            "count": existing.count(),
        }
        for uuid, data in cli_import.hpc_groups.items():
            # The owner is None if its reference was invalid or its user was skipped
            # (see _read_hpcaccess_state()). The group is still imported.
            if data["owner"]:
                owner_username = cli_import.hpc_users[data["owner"]]["username"]
                fk_owner = hpc_users[owner_username]
            else:
                fk_owner = None
            if data["delegate"]:
                delegate_username = cli_import.hpc_users[data["delegate"]]["username"]
                fk_delegate = hpc_users[delegate_username]
            else:
                fk_delegate = None
            old = all.get(data["name"])
            if not old:
                new = HpcGroup(
                    uuid=uuid,
                    name=data["name"],
                    description=data["description"],
                    creator=self.worker_user,
                    owner=fk_owner,
                    delegate=fk_delegate,
                    status=data["status"],
                    gid=data["gid"],
                    folders=data["folders"],
                    resources_requested=data["resources_requested"],
                    resources_used=data["resources_used"],
                    expiration=datetime.fromisoformat(data["expiration"]),
                )
                all[new.name] = new
                update["added"].append(new)
                continue
            changes = {}
            # Without an owner in the file, keep the existing one.
            if fk_owner is not None and (
                old.owner is None or fk_owner.username != old.owner.username
            ):
                changes["owner"] = fk_owner
            # If the file's delegate is a skipped user, keep the existing one.
            if not data["skipped_delegate"] and (
                fk_delegate is not None
                and old.delegate is None
                or fk_delegate is None
                and old.delegate is not None
                or fk_delegate is not None
                and old.delegate is not None
                and fk_delegate.username != old.delegate.username
            ):
                changes["delegate"] = fk_delegate
            for field in (
                "gid",
                "description",
                "status",
                "folders",
                "resources_requested",
            ):
                if (new_field := data[field]) != getattr(old, field):
                    changes[field] = new_field
            if changes:
                update["changed"].append((old, changes))
        return all, update

    def _hpc_projects_update_plan(self, cli_import, hpc_users, hpc_groups):
        names = {data["name"] for data in cli_import.hpc_projects.values()}
        existing = HpcProject.objects.select_for_update()
        all = {obj.name: obj for obj in existing.filter(name__in=names)}
        for project in existing:
            # Force query evaluation by converting to list
            _members = list(project.members.select_for_update())
        update = {
            "added": [],
            "changed": [],
            "missing": existing.exclude(name__in=names),
            "count": existing.count(),
        }
        for uuid, data in cli_import.hpc_projects.items():
            group_name = cli_import.hpc_groups[data["group"]]["name"]
            fk_group = hpc_groups[group_name]
            if data["delegate"]:
                delegate_username = cli_import.hpc_users[data["delegate"]]["username"]
                fk_delegate = hpc_users[delegate_username]
            else:
                fk_delegate = None
            members = []
            for member_uuid in data["members"]:
                fk_member = hpc_users[cli_import.hpc_users[member_uuid]["username"]]
                members.append(fk_member)
            old = all.get(data["name"])
            if not old:
                new = HpcProject(
                    uuid=uuid,
                    name=data["name"],
                    gid=data["gid"],
                    folders=dict(data["folders"]),
                    status=data["status"],
                    creator=self.worker_user,
                    group=fk_group,
                    delegate=fk_delegate,
                    resources_requested=dict(data["resources_requested"]),
                    resources_used=dict(data["resources_used"]),
                    expiration=datetime.fromisoformat(data["expiration"]),
                )
                all[new.name] = new
                update["added"].append((new, members))
                continue
            changes = {}
            if fk_group.name != old.group.name:
                changes["group"] = fk_group
            # If the file's delegate is a skipped user, keep the existing one.
            if not data["skipped_delegate"] and (
                fk_delegate is not None
                and old.delegate is None
                or fk_delegate is None
                and old.delegate is not None
                or fk_delegate is not None
                and old.delegate is not None
                and fk_delegate.username != old.delegate.username
            ):
                changes["delegate"] = fk_delegate
            for field in (
                "gid",
                "folders",
                "status",
                "resources_requested",
            ):
                if (new_field := data[field]) != getattr(old, field):
                    changes[field] = new_field
            old_members = list(old.members.all())
            # Skipped users stay members where they already are.
            members += [m for m in old_members if m.username in data["skipped_members"]]
            old_usernames = {member.username for member in old_members}
            new_usernames = {member.username for member in members}
            if changes or old_usernames ^ new_usernames:
                update["changed"].append((old, changes, members))
        return all, update

    def _create_plan(self, cli_import):
        objects = {}
        updates = {}
        objects["users"], updates["users"] = self._users_update_plan(cli_import)
        objects["hpc_users"], updates["hpc_users"] = self._hpc_users_update_plan(
            cli_import, objects["users"]
        )
        objects["hpc_groups"], updates["hpc_groups"] = self._hpc_groups_update_plan(
            cli_import, objects["hpc_users"]
        )
        objects["hpc_projects"], updates["hpc_projects"] = self._hpc_projects_update_plan(
            cli_import, objects["hpc_users"], objects["hpc_groups"]
        )
        return objects, updates

    def _print_summary(self, updates):
        missing_entries = 0
        for title, update in [
            ("User", updates["users"]),
            ("HpcUser", updates["hpc_users"]),
            ("HpcGroup", updates["hpc_groups"]),
            ("HpcProject", updates["hpc_projects"]),
        ]:
            missing_entries += len(update["missing"])
            self.stdout.write(
                f"\n--- {title} updates ---\n"
                f" * {update['count']} initial objects\n"
                f" * {len(update['added'])} added\n"
                f" * {len(update['missing'])} missing\n"
                f" * {len(update['changed'])} changed\n"
            )
        if missing_entries:
            self._warn(f"{missing_entries} records are missing from the state json file.")

    def _execute_plan(self, objects, updates):
        try:
            for new in updates["users"]["added"]:
                new.save()

            for new in updates["hpc_users"]["added"]:
                pg = new.primary_group
                new.primary_group = None
                new.save()
                new.primary_group = pg

            for new in updates["hpc_groups"]["added"]:
                new.save()

            # Save the hpc_users again now that the primary_group objects exist
            for new in updates["hpc_users"]["added"]:
                new.primary_group = objects["hpc_groups"].get(new.primary_group.name)
                new.save()

            for old, changes in (
                updates["users"]["changed"]
                + updates["hpc_users"]["changed"]
                + updates["hpc_groups"]["changed"]
            ):
                if "primary_group" in changes:
                    changes["primary_group"] = objects["hpc_groups"].get(changes["primary_group"])
                self._save_changes(old, changes)

            for new, members in updates["hpc_projects"]["added"]:
                new.save()
                for member in members:
                    new.members.add(member)

            for old, changes, members in updates["hpc_projects"]["changed"]:
                self._save_changes(old, changes)
                old.members.set(members)

        except Exception as ex:
            self.stderr.write(f"Transaction will be aborted due to {type(ex).__name__}: {ex}")
            self.stderr.write(traceback.format_exc())
            raise

    def add_arguments(self, parser):
        parser.add_argument("state_json_file", type=str)
        parser.add_argument(
            "--write",
            action="store_true",
            help="Write the changes to the database.",
        )

    def handle(self, *args, **options):
        self.worker_user = User.objects.get(username="hpc-worker")
        with transaction.atomic():
            cli_import = self._read_hpcaccess_state(options["state_json_file"])
            objects, updates = self._create_plan(cli_import)
            self._print_summary(updates)
            if not options["write"]:
                self.stdout.write(
                    "\nThis was a dry-run. Use the --write flag to update the database."
                )
                return
            self.stdout.write("\nApplying changes to the database, please be patient...")
            with pghistory.context(source="import"):
                self._execute_plan(objects, updates)
            self.stdout.write("Done.")
